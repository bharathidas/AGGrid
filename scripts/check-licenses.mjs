// Licence check - only MIT and Apache-2.0 are allowed in shipped code and as direct dependencies.
//   node scripts/check-licenses.mjs          check what is bundled + direct deps, write THIRD-PARTY-LICENSES.md
//   node scripts/check-licenses.mjs --all    also summarise every installed package (transitive dev tooling)
// "What is bundled" is measured on the real module graph: the widget entry is bundled with esbuild using the
// same externals as the Mendix build (react, react-dom, mendix, big.js), and every node_modules file in the
// graph is attributed to its package. Exit code 1 when anything bundled or any direct dependency is not
// MIT/Apache-2.0.
import { build } from "esbuild";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const ALLOWED = new Set(["MIT", "Apache-2.0"]);
// Provided by the Mendix client at runtime (externals of pluggable-widgets-tools), never bundled.
const EXTERNAL = ["react", "react-dom", "react/jsx-runtime", "mendix", "mendix/*", "big.js"];

function licenceOf(manifest) {
    const value = manifest.license ?? manifest.licenses;
    if (!value) {
        return "UNKNOWN";
    }
    if (typeof value === "string") {
        return value;
    }
    if (Array.isArray(value)) {
        return value.map(entry => entry.type ?? entry).join(" OR ");
    }
    return value.type ?? "UNKNOWN";
}

/** An SPDX expression passes when one OR alternative, or every AND part, is allowed. */
function allowed(expression) {
    const clean = expression.replace(/[()]/g, " ").replace(/\s+/g, " ").trim();
    if (clean.includes(" OR ")) {
        return clean.split(" OR ").some(part => allowed(part));
    }
    if (clean.includes(" AND ")) {
        return clean.split(" AND ").every(part => allowed(part));
    }
    return ALLOWED.has(clean);
}

function packageRoot(file) {
    const parts = file.split(/[\\/]/);
    const index = parts.lastIndexOf("node_modules");
    if (index < 0) {
        return undefined;
    }
    const depth = parts[index + 1].startsWith("@") ? 3 : 2;
    return parts.slice(0, index + depth).join(sep);
}

const entry = join(root, "src", `${pkg.widgetName}.tsx`);
const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    metafile: true,
    format: "esm",
    jsx: "automatic",
    external: EXTERNAL,
    loader: { ".css": "empty", ".png": "empty" },
    logLevel: "silent"
});
const bundled = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
    const dir = packageRoot(join(root, input));
    if (!dir) {
        continue;
    }
    const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    bundled.set(`${manifest.name}@${manifest.version}`, {
        name: manifest.name,
        version: manifest.version,
        licence: licenceOf(manifest),
        url:
            manifest.homepage ??
            (typeof manifest.repository === "string" ? manifest.repository : manifest.repository?.url) ??
            ""
    });
}

const direct = [...Object.keys(pkg.dependencies ?? {}), ...Object.keys(pkg.devDependencies ?? {})].map(name => {
    const manifestPath = join(root, "node_modules", name, "package.json");
    const manifest = existsSync(manifestPath)
        ? JSON.parse(readFileSync(manifestPath, "utf8"))
        : { version: "?", license: "MISSING" };
    return { name, version: manifest.version, licence: licenceOf(manifest), dev: !(name in (pkg.dependencies ?? {})) };
});

const rows = [...bundled.values()].sort((a, b) => a.name.localeCompare(b.name));
const bad = [...rows.filter(row => !allowed(row.licence)), ...direct.filter(row => !allowed(row.licence))];

const lines = [
    `# Third-party licences - ${pkg.widgetName}`,
    "",
    "Policy: only MIT and Apache-2.0 licensed code is shipped. Generated by `node scripts/check-licenses.mjs` from the real",
    "module graph of the widget bundle.",
    "",
    "## Bundled into the widget",
    "",
    "| Package | Version | Licence | Source |",
    "| --- | --- | --- | --- |",
    ...(rows.length
        ? rows.map(row => `| ${row.name} | ${row.version} | ${row.licence} | ${row.url.replace(/^git\+/, "")} |`)
        : ["| (none) | | | |"]),
    "",
    "## Provided by the Mendix runtime (not bundled)",
    "",
    "`react`, `react-dom`, the `mendix` client APIs and `big.js` (MIT) are externals supplied by the Mendix client.",
    "",
    "## Direct dependencies",
    "",
    "| Package | Version | Licence | Kind |",
    "| --- | --- | --- | --- |",
    ...direct.map(row => `| ${row.name} | ${row.version} | ${row.licence} | ${row.dev ? "development" : "runtime"} |`),
    "",
    "The browser harness drives a locally installed Chromium-based browser (set CHROME_PATH to an open-source Chromium build).",
    ""
];
writeFileSync(join(root, "THIRD-PARTY-LICENSES.md"), lines.join("\n"));

console.log(`bundled packages: ${rows.length}`);
rows.forEach(row => console.log(`  ${allowed(row.licence) ? "ok " : "BAD"} ${row.name}@${row.version} ${row.licence}`));
console.log("direct dependencies:");
direct.forEach(row =>
    console.log(
        `  ${allowed(row.licence) ? "ok " : "BAD"} ${row.name}@${row.version} ${row.licence}${row.dev ? " (dev)" : ""}`
    )
);
console.log(`disallowed: ${bad.length}`);

if (process.argv.includes("--all")) {
    const summary = new Map();
    const walk = dir => {
        if (!existsSync(dir)) {
            return;
        }
        for (const name of readdirSync(dir)) {
            if (name.startsWith(".")) {
                continue;
            }
            const full = join(dir, name);
            if (name.startsWith("@")) {
                walk(full);
                continue;
            }
            const manifestPath = join(full, "package.json");
            if (existsSync(manifestPath)) {
                const licence = licenceOf(JSON.parse(readFileSync(manifestPath, "utf8")));
                summary.set(licence, (summary.get(licence) ?? 0) + 1);
                walk(join(full, "node_modules"));
            }
        }
    };
    walk(join(root, "node_modules"));
    console.log("\nall installed packages (transitive dev tooling, not shipped):");
    [...summary.entries()]
        .sort((a, b) => b[1] - a[1])
        .forEach(([licence, count]) => console.log(`  ${allowed(licence) ? "   " : " ! "}${licence}: ${count}`));
}

process.exit(bad.length ? 1 : 0);
